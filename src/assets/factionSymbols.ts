/**
 * Retrieves the official verified symbol for any faction and subfaction.
 * If the subfaction lacks an individual symbol, automatically falls back to
 * the parent faction's official symbol.
 */
export function getFactionSymbol(
  factionId?: string,
  subfactionId?: string,
  variant: 'white' | 'black' = 'white'
): ImageSourcePropType | null {
  const catalog = variant === 'black' ? FACTION_SYMBOLS_BLACK : FACTION_SYMBOLS;

  // 1. Check if specific subfaction symbol exists
  if (subfactionId && catalog[subfactionId]) {
    return catalog[subfactionId];
  }

  // 2. Check if direct parent faction symbol exists
  if (factionId && catalog[factionId]) {
    return catalog[factionId];
  }

  // 3. Fallback to default symbol for the faction
  if (factionId && FACTION_DEFAULT_SYMBOL_MAP[factionId]) {
    const defaultSymId = FACTION_DEFAULT_SYMBOL_MAP[factionId];
    if (catalog[defaultSymId]) {
      return catalog[defaultSymId];
    }
  }

  return null;
}
