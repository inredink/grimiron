/**
 * Quick index mapping achievement ID to its definition.
 */
export const ACHIEVEMENT_MAP = new Map<string, AchievementDefinition>(
  ACHIEVEMENT_CATALOG.map((a) => [a.id, a])
);

/**
 * Filters achievements by scope and/or category.
 */
export function getAchievementsByScope(scope?: string): AchievementDefinition[] {
  if (!scope || scope === 'all') return ACHIEVEMENT_CATALOG;
  return ACHIEVEMENT_CATALOG.filter((a) => a.scope === scope);
}

export function getAchievementsByCategory(category?: string): AchievementDefinition[] {
  if (!category || category === 'all') return ACHIEVEMENT_CATALOG;
  return ACHIEVEMENT_CATALOG.filter((a) => a.category === category);
}
