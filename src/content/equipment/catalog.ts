export function getEquipmentById(id: string): EquipmentDefinition | undefined {
  return EQUIPMENT_CATALOG.find((item) => item.id === id);
}

export function getStarterEquipmentForFaction(factionId: string): EquipmentDefinition[] {
  return EQUIPMENT_CATALOG.filter(
    (item) => item.isStarterItem && (item.compatibleFactions.includes(factionId) || item.compatibleFactions.includes('all'))
  );
}

export function getEquipmentForSlot(
  slot: string,
  factionId: string
): EquipmentDefinition[] {
  return EQUIPMENT_CATALOG.filter(
    (item) =>
      item.slot === slot &&
      (item.compatibleFactions.includes(factionId) || item.compatibleFactions.includes('all'))
  );
}
