/**
 * Helper to retrieve a training program by its unique ID.
 */
export function getProgramById(programId: string): TrainingProgramDefinition | undefined {
  return TRAINING_PROGRAM_CATALOG.find((p) => p.id === programId);
}

/**
 * Filter programs by category.
 */
export function getProgramsByCategory(category: ProgramCategory): TrainingProgramDefinition[] {
  return TRAINING_PROGRAM_CATALOG.filter((p) => p.category === category);
}

/**
 * Create a customizable custom program template.
 */
export function createCustomProgramTemplate(
  title: string,
  description: string,
  sessions: ScheduledProgramSession[]
): TrainingProgramDefinition {
  return {
    id: `prog_custom_${Date.now()}`,
    title,
    shortDescription: description.slice(0, 80),
    description,
    category: 'custom',
    difficulty: 'intermediate',
    trainingEmphasis: 'hybrid',
    durationWeeks: 4,
    frequencyDaysPerWeek: sessions.filter((s) => !s.isRestDay).length,
    isCanonical: false,
    sourceNote: 'User-created custom training program.',
    customizable: true,
    iconName: 'construct-outline',
    tags: ['custom', 'user-generated'],
    blocks: [
      {
        blockNumber: 1,
        title: 'Custom Block 1',
        focus: 'User-defined workout progression',
        durationWeeks: 4,
        sessions,
      },
    ],
  };
}
