/**
 * Resolves all available attacks for a faction, including any subfaction overrides or extensions.
 */
export function getAttacksForFaction(
  factionId: string,
  subfactionId?: string
): FactionAttackDefinition[] {
  if (!factionId) return [...DEFAULT_FALLBACK_ATTACKS];

  const parentAttacks = FACTION_ATTACKS_CATALOG.filter(
    (a) => a.factionId === factionId && !a.subfactionId
  );

  if (!subfactionId) {
    return parentAttacks.length > 0 ? parentAttacks : [...DEFAULT_FALLBACK_ATTACKS];
  }

  const subfactionAttacks = FACTION_ATTACKS_CATALOG.filter(
    (a) => a.factionId === factionId && a.subfactionId === subfactionId
  );

  // Return combined pool with subfaction-specific attacks alongside parent faction attacks
  return [...subfactionAttacks, ...parentAttacks];
}

/**
 * Resolves a single faction attack definition deterministically.
 *
 * Priority Rules:
 * 1. Subfaction-specific attack matching requested category (subfaction override).
 * 2. Parent-faction attack matching requested category.
 * 3. Any subfaction-specific attack if category has no direct match.
 * 4. Any parent-faction attack if category has no direct match.
 * 5. Safe default fallback attack matching category.
 */
export function resolveFactionAttack(options: {
  factionId?: string;
  subfactionId?: string;
  category?: AttackCategory;
  seed?: string | number;
}): FactionAttackDefinition {
  const { factionId, subfactionId, category = 'ranged', seed = 0 } = options;

  if (!factionId) {
    const fallbackList = DEFAULT_FALLBACK_ATTACKS.filter((a) => a.category === category);
    return fallbackList.length > 0 ? fallbackList[0] : DEFAULT_FALLBACK_ATTACKS[0];
  }

  // 1. Subfaction category override
  if (subfactionId) {
    const subMatches = FACTION_ATTACKS_CATALOG.filter(
      (a) => a.factionId === factionId && a.subfactionId === subfactionId && a.category === category
    );
    if (subMatches.length > 0) {
      return deterministicPick(subMatches, seed);
    }
  }

  // 2. Parent faction category match
  const parentMatches = FACTION_ATTACKS_CATALOG.filter(
    (a) => a.factionId === factionId && !a.subfactionId && a.category === category
  );
  if (parentMatches.length > 0) {
    return deterministicPick(parentMatches, seed);
  }

  // 3. Any subfaction attack
  if (subfactionId) {
    const anySub = FACTION_ATTACKS_CATALOG.filter(
      (a) => a.factionId === factionId && a.subfactionId === subfactionId
    );
    if (anySub.length > 0) {
      return deterministicPick(anySub, seed);
    }
  }

  // 4. Any parent faction attack
  const anyParent = FACTION_ATTACKS_CATALOG.filter(
    (a) => a.factionId === factionId && !a.subfactionId
  );
  if (anyParent.length > 0) {
    return deterministicPick(anyParent, seed);
  }

  // 5. Fallback
  const fallbackList = DEFAULT_FALLBACK_ATTACKS.filter((a) => a.category === category);
  return fallbackList.length > 0 ? fallbackList[0] : DEFAULT_FALLBACK_ATTACKS[0];
}

/**
 * Deterministically picks an item from a list based on an input seed (e.g. set.id).
 * Guarantees variety across consecutive sets while ensuring 100% idempotent results
 * on screen refreshes or combat state recalculations.
 */
function deterministicPick<T>(items: T[], seed: string | number): T {
  if (items.length === 0) {
    throw new Error('deterministicPick called with empty array');
  }
  let hash = 0;
  const str = String(seed);
  for (let i = 0; i < str.length; i++) {
    hash = (hash * 31 + str.charCodeAt(i)) >>> 0;
  }
  return items[hash % items.length];
}
