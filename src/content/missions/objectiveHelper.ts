import { MissionObjectiveDefinition } from '../../types/mission';
import { getEnemyById } from '../combat/enemies';

export interface ObjectiveGuidance {
  badge: string;
  title: string;
  explanation: string;
  howToComplete: string;
  metricLabel: string;
}

/**
 * Returns comprehensive, educational plain-English guidance explaining
 * exactly what an operation objective involves and how to fulfill it.
 */
export function getObjectiveGuidance(obj: MissionObjectiveDefinition): ObjectiveGuidance {
  switch (obj.type) {
    case 'complete_workouts':
      return {
        badge: 'CRUSADE LOGISTICS',
        title: 'Complete Training Deployments',
        explanation:
          'This objective tests your consistency in the iron temple. You must execute and finish complete workout sessions without prematurely abandoning them.',
        howToComplete:
          'Start any workout session (from your active training program, tactical deployment, or custom session), log your sets, and tap "Complete Mission" at the finish.',
        metricLabel: 'Workouts Completed',
      };

    case 'complete_sets':
      return {
        badge: 'WORKING SETS',
        title: 'Accumulate Working Sets',
        explanation:
          'Every completed working set serves as a kinetic strike against enemy positions. Warm-up sets are excluded—only dedicated working sets count.',
        howToComplete:
          'Add exercises to your workout and tap the checkmark on each set after performing it. Both dumbbell, barbell, machine, and bodyweight sets qualify.',
        metricLabel: 'Valid Working Sets',
      };

    case 'volume_kg':
      return {
        badge: 'BATTLE TONNAGE',
        title: 'Move Heavy Iron Tonnage',
        explanation:
          'Total work capacity is measured in cumulative tonnage. Tonnage equals the weight moved multiplied by the number of repetitions completed across all working sets (Weight × Reps).',
        howToComplete:
          'Prioritize compound movements (Squats, Deadlifts, Bench Press, Rows) and consistent set volume. Heavier working weights rapidly advance this objective.',
        metricLabel: 'Cumulative Tonnage (kg)',
      };

    case 'target_reps':
      return {
        badge: 'ENDURANCE DOCTRINE',
        title: 'Repetition Stamina',
        explanation:
          'A test of muscle endurance and physical stamina under sustained tension. Every completed repetition is tracked.',
        howToComplete:
          'Execute clean, controlled repetitions across all sets. High-repetition accessory movements and German Volume Training protocols advance this rapidly.',
        metricLabel: 'Total Repetitions',
      };

    case 'exercise_category_sets': {
      const category = (obj.exerciseCategory || 'targeted').toUpperCase();
      return {
        badge: `${category} DOCTRINE`,
        title: `Targeted Muscle Discipline: ${category}`,
        explanation: `Imperial command mandates specialized conditioning of the ${category} muscle group. Only exercises classified under this anatomy qualify.`,
        howToComplete: `Select exercises in the library matching the "${category}" category (e.g. for Chest: Bench Press, Incline DB Press, Dips, Cable Flyes) and perform working sets.`,
        metricLabel: `${category} Working Sets`,
      };
    }

    case 'combat_damage':
      return {
        badge: 'FIREPOWER DEPLOYMENT',
        title: 'Inflict Kinetic Combat Damage',
        explanation:
          'Combat damage is generated by the tonnage and intensity of your working sets during an active mission encounter. Higher loads inflict crushing strikes.',
        howToComplete:
          'Engage a target enemy during your workout. As you complete sets with high weight and intensity, damage is applied directly to the enemy hostile.',
        metricLabel: 'Combat Damage Dealt',
      };

    case 'combat_attacks':
      return {
        badge: 'TACTICAL SALVO',
        title: 'Deliver Combat Attacks',
        explanation:
          'Each completed working set in an armed mission delivers a tactical attack (Bolter fire, Chainsword slash, or Plasma burst) against the hostile.',
        howToComplete:
          'Arm an active mission target on the workout terminal and check off completed sets. Each completed set triggers an attack event.',
        metricLabel: 'Combat Strikes Landed',
      };

    case 'defeat_enemy': {
      const enemy = obj.enemyId ? getEnemyById(obj.enemyId) : undefined;
      const enemyName = enemy?.name || 'the designated hostile target';
      return {
        badge: 'HOSTILE PURGE',
        title: `Neutralize: ${enemyName}`,
        explanation: `This operation requires the total destruction of ${enemyName}. You must deplete their hit points to zero before your workout concludes.`,
        howToComplete: `Select ${enemyName} as your mission target in the Crusade terminal, then perform enough heavy sets and tonnage to deplete their HP bar completely.`,
        metricLabel: 'Target Status',
      };
    }

    case 'coop_attacks':
      return {
        badge: 'SQUAD COOPERATION',
        title: 'Multiplayer Raid Strikes',
        explanation:
          'Join forces with battle-brothers in the Cooperative Raid Terminal. Your workout sets deal coordinated damage to massive raid bosses.',
        howToComplete:
          'Deploy into an active Co-op Boss Raid from the Warfront terminal and log completed sets to contribute collective damage to the squad queue.',
        metricLabel: 'Squad Attacks Contributed',
      };

    case 'coop_raid_slain':
      return {
        badge: 'RAID CONQUEST',
        title: 'Slay Cooperative Raid Boss',
        explanation:
          'Requires the total defeat of a multi-warrior raid boss encounter alongside your squad.',
        howToComplete:
          'Coordinate with other operatives to reduce the weekly co-op raid boss to 0 HP and claim victory rewards.',
        metricLabel: 'Raid Boss Victories',
      };

    case 'pr_broken':
      return {
        badge: 'MAXIMUM OVERLOAD',
        title: 'Establish Personal Records',
        explanation:
          'Progressive overload is the foundation of strength. You must surpass your previous all-time best weight or set volume on any cataloged lift.',
        howToComplete:
          'Increase the weight or reps on an exercise beyond your historical personal best and record the completed set.',
        metricLabel: 'Personal Records (PRs)',
      };

    case 'rest_days_honored':
      return {
        badge: 'RECOVERY LITANY',
        title: 'Tactical Recovery Days',
        explanation:
          'Hypertrophy and physical fortitude are rebuilt during strategic downtime. Scheduled rest days must be observed to allow recovery.',
        howToComplete:
          'When following an active training program, mark scheduled rest days as completed in the Training Program Center.',
        metricLabel: 'Rest Days Observed',
      };

    default:
      return {
        badge: 'TACTICAL DIRECTIVE',
        title: obj.description,
        explanation:
          'Complete the specified training objectives to advance this faction operation and earn military honorifics.',
        howToComplete:
          'Log your workout sets and follow the criteria outlined in your Chapter mission briefing.',
        metricLabel: 'Objective Progress',
      };
  }
}
